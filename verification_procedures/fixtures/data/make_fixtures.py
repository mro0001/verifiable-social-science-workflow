"""Build the data-stream fixtures: a tiny synthetic survey project, clean and seeded.

    python3 fixtures/data/make_fixtures.py

clean/ holds the hand-written project sources (params_io.py, s1_clean.py,
s2_describe.py, s3_model.py, params.yaml, pipeline.yaml). This script:
  1. writes the synthetic raw data (seeded RNG, invented values, no real data),
  2. records its hash in acquisition.yaml,
  3. RUNS the pipeline to produce every committed output, then writes numbers.yml
     from those outputs;
  4. copies the sources to seeded/, applies the script-level faults and the AI's
     change to params.yaml, runs the pipeline there too (the author ran the faulty
     code), and only THEN plants the after-the-run faults: raw edited after
     acquisition, a hand-edited table, a stale model record, a hand-typed manuscript
     number;
  5. writes each fixture's record of the AI's file edits (file_edits.yaml), in the
     form the audit layer writes it out, naming the AI's changes in that fixture.
Rerunning it rewrites both fixtures identically.
"""
import csv
import hashlib
import json
import os
import random
import shutil
import subprocess
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
CLEAN, SEEDED = os.path.join(HERE, "clean"), os.path.join(HERE, "seeded")
SOURCES = ["params_io.py", "s1_clean.py", "s2_describe.py", "s3_model.py", "params.yaml", "pipeline.yaml"]
REGIONS = ["East", "North", "South", "West"]

# The AI's changes the record names (synthetic sessions). E01 is in both fixtures, a comment
# the AI reworded with a stated reason. E02 and E03 are in the seeded fixture only, the AI's
# change to drop_missing with no stated reason (it now drops missing age, not income) and
# the AI's change to fig_width with a stated reason.
DROP_INCOME = 'return [r for r in rows if r["income"].strip() != ""]'
DROP_AGE = 'return [r for r in rows if r["age"].strip() != ""]'
FIG_480 = "fig_width: 480         # describe: figure width, pixels"
FIG_520 = "fig_width: 520         # describe: figure width, pixels"
E01 = {"id": "e01", "path": "s2_describe.py", "kind": "edit",
       "before": "        # A blank income_k is skipped in the mean.",
       "after": "        # A blank income_k is skipped in the mean and counted, never dropped silently.",
       "rationale": "Say that a blank income is counted as well as skipped, since n_missing shows it.",
       "session": "2b7e0a14-5c3d-4e21-9f80-1a2b3c4d5e6f", "session_ref": "S5a0c91e7d2b4"}
E02 = {"id": "e02", "path": "s1_clean.py", "kind": "edit",
       "before": "    " + DROP_INCOME, "after": "    " + DROP_AGE, "rationale": "",
       "session": "2b7e0a14-5c3d-4e21-9f80-1a2b3c4d5e6f", "session_ref": "S5a0c91e7d2b4"}
E03 = {"id": "e03", "path": "params.yaml", "kind": "edit", "before": FIG_480, "after": FIG_520,
       "rationale": "Widen the figure so the four region labels do not crowd each other.",
       "session": "9c1d0b25-6e4f-4a32-8b91-2c3d4e5f6a7b", "session_ref": "S7f3e2d1c0b9a"}
RECORD_HEAD = """# The record of the AI's file edits (synthetic), as the audit layer writes it out. Each
# entry is one edit an AI tool call made to a file in the project, with the text before
# and after and the reason the AI stated before it. An empty rationale is an AI change with
# no recorded reason. Planted faults, if any, are listed in truth.yaml.
"""


def sha(p):
    with open(p, "rb") as f:
        return "sha256:" + hashlib.sha256(f.read()).hexdigest()


def write_raw(d):
    rng = random.Random(2026)
    rows = []
    for i in range(1, 49):
        region = REGIONS[i % 4]
        age = rng.randint(19, 78)
        income = round(rng.uniform(22000, 140000), -2)
        sat = min(5, max(1, round(1.2 + income / 40000 + rng.uniform(-1.0, 1.0))))
        rows.append({"id": i, "region": region, "age": age, "income": int(income), "satisfaction": sat})
    for i in (5, 22):            # minors: dropped by min_age
        rows[i - 1]["age"] = 16
    for i in (9, 31, 40):        # blank income: dropped by drop_missing
        rows[i - 1]["income"] = ""
    for i in (14, 37):           # blank age: excluded by the age rule
        rows[i - 1]["age"] = ""
    for i in (12, 27):           # above the cap: top-coded
        rows[i - 1]["income"] = 310000 + 1000 * i
    with open(os.path.join(d, "raw_survey.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["id", "region", "age", "income", "satisfaction"], lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def write_acquisition(d):
    text = ("# Raw data is immutable. Each raw file's hash is recorded at acquisition;\n"
            "# a later edit shows up as a hash mismatch even when outputs still reproduce.\n"
            "raw:\n"
            "  - file: raw_survey.csv\n"
            "    sha256: %s\n"
            "    source: \"Synthetic survey generated by fixtures/data/make_fixtures.py (random.Random(2026)); invented values\"\n"
            "    collected: 2026-10-08\n" % sha(os.path.join(d, "raw_survey.csv")))
    with open(os.path.join(d, "acquisition.yaml"), "w") as f:
        f.write(text)


def run_pipeline(d):
    with open(os.path.join(d, "pipeline.yaml")) as f:
        pipe = yaml.safe_load(f)
    for s in pipe["steps"]:
        p = subprocess.run([sys.executable, s["script"]], cwd=d, capture_output=True, text=True,
                           env=dict(os.environ, PYTHONDONTWRITEBYTECODE="1"))
        if p.returncode:
            sys.exit("%s failed in %s:\n%s" % (s["script"], d, p.stderr))


def cell(d, fname, field, where):
    with open(os.path.join(d, fname), newline="") as f:
        for r in csv.DictReader(f):
            if all(r[k] == v for k, v in where.items()):
                return r[field]
    raise KeyError((fname, field, where))


def write_numbers(d, override=None):
    with open(os.path.join(d, "model_record_model.json")) as f:
        n = json.load(f)["n"]
    keys = [
        ("n_analytic", str(n), "model_record_model.json", "n", None),
        ("slope_income_k", cell(d, "table_model.csv", "estimate", {"term": "income_k"}),
         "table_model.csv", "estimate", {"term": "income_k"}),
        ("p_income_k", cell(d, "table_model.csv", "p", {"term": "income_k"}),
         "table_model.csv", "p", {"term": "income_k"}),
        ("mean_income_k_north", cell(d, "table_descriptives.csv", "mean_income_k", {"region": "North"}),
         "table_descriptives.csv", "mean_income_k", {"region": "North"}),
        ("alpha", cell(d, "params_record_model.csv", "value", {"param": "alpha"}),
         "params_record_model.csv", "value", {"param": "alpha"}),
    ]
    lines = ["# Manuscript numbers. Prose cites {{num:<key>}}; each value must equal the",
             "# replayed output it names (from + field, optionally where). Display strings.",
             "numbers:"]
    for key, value, src, field, where in keys:
        if override and key in override:
            value = override[key]
        w = "" if not where else ", where: {%s}" % ", ".join("%s: %s" % kv for kv in where.items())
        lines.append('  %s: {value: "%s", from: %s, field: %s%s}' % (key, value, src, field, w))
    with open(os.path.join(d, "numbers.yml"), "w") as f:
        f.write("\n".join(lines) + "\n")


def replace_once(path, old, new):
    with open(path) as f:
        text = f.read()
    assert text.count(old) == 1, (path, old)
    with open(path, "w") as f:
        f.write(text.replace(old, new))


def write_record(d, entries):
    with open(os.path.join(d, "file_edits.yaml"), "w") as f:
        f.write(RECORD_HEAD + yaml.safe_dump(entries, sort_keys=False, default_flow_style=False,
                                             allow_unicode=True, width=4096))


def build_clean():
    for name in os.listdir(CLEAN):
        if name not in SOURCES:
            os.remove(os.path.join(CLEAN, name))
    write_raw(CLEAN)
    write_acquisition(CLEAN)
    run_pipeline(CLEAN)
    write_numbers(CLEAN)
    write_record(CLEAN, [E01])


def build_seeded():
    if os.path.exists(SEEDED):
        shutil.rmtree(SEEDED)
    os.makedirs(SEEDED)
    for name in SOURCES + ["raw_survey.csv", "acquisition.yaml"]:
        shutil.copy2(os.path.join(CLEAN, name), os.path.join(SEEDED, name))
    s1 = os.path.join(SEEDED, "s1_clean.py")
    # F7: the AI changed drop_missing with no stated reason (record e02). The comment and
    # docstring still say income; the code now drops missing AGE.
    replace_once(s1, DROP_INCOME, DROP_AGE)
    # F2: a hard-coded threshold that differs from params.yaml (min_age: 18).
    replace_once(s1, 'min_age = P["min_age"]', "min_age = 21")
    # F6: s2_describe.py loses its Inputs/Outputs/Parameters/Assumptions sections.
    s2 = os.path.join(SEEDED, "s2_describe.py")
    with open(s2) as f:
        text = f.read()
    end = text.index('"""', 3) + 3
    with open(s2, "w") as f:
        f.write('"""Describe income and satisfaction by region.\n\nPurpose:\n'
                '    Summarize the analytic file by region.\n"""' + text[end:])
    # F9: the AI set fig_width (record e03), with a stated reason.
    replace_once(os.path.join(SEEDED, "params.yaml"), FIG_480, FIG_520)
    # The author ran this code: committed outputs are what it produced.
    run_pipeline(SEEDED)
    write_numbers(SEEDED)
    raw = os.path.join(SEEDED, "raw_survey.csv")
    # F1: raw edited after acquisition, on a row the pipeline drops (a minor), so
    # every output still reproduces and only the acquisition hash shows the edit.
    with open(raw) as f:
        lines = f.read().split("\n")
    i = next(k for k, ln in enumerate(lines) if ln.startswith("5,"))
    parts = lines[i].split(",")
    parts[-1] = "5" if parts[-1] != "5" else "4"
    lines[i] = ",".join(parts)
    with open(raw, "w") as f:
        f.write("\n".join(lines))
    # F3: a hand-edited cell in the descriptive table.
    tab = os.path.join(SEEDED, "table_descriptives.csv")
    with open(tab) as f:
        rows = f.read().split("\n")
    j = next(k for k, ln in enumerate(rows) if ln.startswith("South,"))
    parts = rows[j].split(",")
    parts[3] = "%.3f" % (float(parts[3]) + 4.5)
    rows[j] = ",".join(parts)
    with open(tab, "w") as f:
        f.write("\n".join(rows))
    # F4: the model record carries the hash of an older params.yaml (alpha was 0.10).
    old = os.path.join(HERE, "_old_params.yaml")
    with open(os.path.join(SEEDED, "params.yaml")) as f:
        older = f.read().replace("alpha: 0.05 ", "alpha: 0.10 ")
    with open(old, "w") as f:
        f.write(older)
    old_hash = sha(old)
    os.remove(old)
    rec = os.path.join(SEEDED, "model_record_model.json")
    with open(rec) as f:
        r = json.load(f)
    r["params_sha256"] = old_hash
    with open(rec, "w") as f:
        json.dump(r, f, indent=2, sort_keys=True)
        f.write("\n")
    # F5: a manuscript number typed by hand from an earlier draft.
    slope = cell(SEEDED, "table_model.csv", "estimate", {"term": "income_k"})
    write_numbers(SEEDED, override={"slope_income_k": "%.3f" % (float(slope) + 0.004)})
    truth = """# Planted faults in the seeded data project. item matches the finding's item field.
faults:
  - {id: F1, check: check_raw, item: raw_survey.csv}          # raw edited after acquisition (on a dropped row)
  - {id: F2, check: check_params, item: s1_clean.py}          # min_age = 21 hard-coded; params.yaml says 18
  - {id: F3, check: replay_pipeline, item: table_descriptives.csv}  # hand-edited South mean_income_k
  - {id: F4, check: check_records, item: model_record_model.json}   # params hash from an older params.yaml
  - {id: F5, check: check_numbers, item: slope_income_k}      # typed by hand; does not reproduce from table_model.csv
  - {id: F6, check: check_docs, item: s2_describe.py}         # docstring lost Inputs/Outputs/Parameters/Assumptions
  - {id: F7, check: attribute_ai, item: e02}                  # the AI changed drop_missing in s1_clean.py with no stated reason
  - {id: F8, check: replay_pipeline, item: s3_model.py}       # stderr warning: rows dropped (consequence of F7)
  - {id: F9, check: attribute_ai, item: "params.yaml:fig_width"}  # a parameter the AI changed, 480 to 520
"""
    with open(os.path.join(SEEDED, "truth.yaml"), "w") as f:
        f.write(truth)
    write_record(SEEDED, [E01, E02, E03])


if __name__ == "__main__":
    build_clean()
    build_seeded()
    print("clean:", sorted(os.listdir(CLEAN)))
    print("seeded:", sorted(os.listdir(SEEDED)))
